"""Extracts the site nav and footer from about.html into lib/blog/chrome.js so blog posts (rendered by a
serverless function at /blog/<slug>) always carry the same chrome. Re-run after the nav or footer changes."""
import re, json
s = open('about.html').read()
nav = re.search(r'<nav class="site-nav".*?</nav>', s, re.S).group(0)
foot = re.search(r'<footer .*?</footer>', s, re.S).group(0)

def absolute(h):
    # pages live at /blog/<slug>, so relative links must become root-relative
    def fix(m):
        attr, q, url = m.group(1), m.group(2), m.group(3)
        if re.match(r'(https?:|mailto:|tel:|#|/|data:)', url): return m.group(0)
        return f'{attr}={q}/{url}{q}'
    return re.sub(r'\b(href|src)=(["\'])([^"\']*)\2', fix, h)

out = '// Generated by scripts/build-blog-chrome.py. Do not edit by hand.\n'
out += 'export const NAV = ' + json.dumps(absolute(nav)) + ';\n'
out += 'export const FOOTER = ' + json.dumps(absolute(foot)) + ';\n'
open('lib/blog/chrome.js', 'w').write(out)
print('nav', len(nav), 'footer', len(foot))

#!/usr/bin/env python3
"""Generates lib/blog/icons.js from the design system's Tabler icon set (DOXA Design System v1/assets/icons).
Run after changing the ICONS list below. The icons in that folder are the filled Tabler variants."""
import re, os
SRC = '/Users/samanthabarnes/Claude/DOXA Design System v1/assets/icons'
ICONS = ['article', 'briefcase', 'school', 'microphone', 'building-broadcast-tower', 'file-download', 'map-pin', 'search', 'download', 'check', 'chevron-down']
out = ['// Generated by scripts/build-blog-icons.py from the design system Tabler icons (filled). Do not edit by hand.',
       'const PATHS = {']
for n in ICONS:
    s = open(os.path.join(SRC, n + '.svg')).read()
    paths = [p for p in re.findall(r'<path\b[^>]*>', s) if 'stroke="none"' not in p]
    d = ' '.join(re.findall(r'\sd="([^"]+)"', ' '.join(paths)))
    out.append(f"  '{n}': {d!r},")
out += ['};', '',
        '// Inline icon markup. Decorative by default (aria-hidden); colour comes from currentColor.',
        "export const icon = (name, size = 16) => `<svg viewBox=\"0 0 24 24\" width=\"${size}\" height=\"${size}\" fill=\"currentColor\" aria-hidden=\"true\" focusable=\"false\"><path d=\"${PATHS[name]}\"/></svg>`;",
        'export const iconPath = (name) => PATHS[name];', '']
open('lib/blog/icons.js', 'w').write('\n'.join(out))
print('wrote lib/blog/icons.js', len(ICONS), 'icons')
